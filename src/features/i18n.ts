export default i18n;
export function localidade() {
  return i18n.language === 'en' ? 'en-GB' : i18n.language === 'es' ? 'es-ES' : 'pt-BR';
}
export function formatarData(
  valor: string,
  opcoes: Intl.DateTimeFormatOptions = { day: '2-digit', month: 'short', year: 'numeric' },
) {
  return new Intl.DateTimeFormat(localidade(), opcoes).format(
    new Date(valor.length === 10 ? `${valor}T12:00:00` : valor),
  );
}
export function nomePais(codigo: string) {
  return new Intl.DisplayNames([localidade()], { type: 'region' }).of(codigo) ?? codigo;
}
export function nomeIdioma(codigo: string) {
  try {
    return new Intl.DisplayNames([localidade()], { type: 'language' }).of(codigo) ?? codigo;
  } catch {
    return codigo;
  }
}
